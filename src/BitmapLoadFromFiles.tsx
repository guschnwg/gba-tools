function assemblyToBitmap(assembly: string, width: number): number[][] {
    const tilesData = assembly.split('.section')[1].split('Bitmap:')[1];
    const rows = tilesData.trim().split('\n').map(r => r.trim()).filter(Boolean);
    const pixelsInGBAHex = rows.map(r => r.split(' ')[1].split(',')).flat();
    const withoutHexPart = pixelsInGBAHex.map(item => item.replace('0x', ''));
    const pixels = withoutHexPart.map(groupOf4 => chunks(groupOf4.split(''), 2).map(numbers => numbers.join(''))).map(groupOf4 => groupOf4.reverse()).flat();
    const pixelsInNumber = pixels.map(pixel => parseInt(pixel, 16));

    return chunks(pixelsInNumber, width);
}

function assemblyToPalette(assembly: string): { r: number, g: number, b: number }[] {
    const paletteData = assembly.split('Pal:')[1];
    const rows = paletteData.trim().split('\n').map(r => r.trim()).filter(Boolean);
    const paletteInGBAHex = rows.map(r => r.split(' ')[1].split(',')).flat()
    return paletteInGBAHex.map(color => {
        const asNumber = parseInt(color, 16);
        return {
            r: asNumber & 0b11111,
            g: (asNumber >> 5) & 0b11111,
            b: (asNumber >> 10) & 0b11111,
        }
    });
}

export function BitmapLoadFromFiles({
    onLoad
}: {
    onLoad: (palette: { r: number, g: number, b: number }[], bitmap: number[][]) => void
}) {
    const [type, setType] = useState<'random' | 'storage' | 'files'>('random');

    const [header, setHeader] = useState(DEFAULT_HEADER);
    const [assembly, setAssembly] = useState(DEFAULT_ASM);

    const palette = useMemo<{ r: number, g: number, b: number }[]>(() => {
        if (!assembly) return [];
        return assemblyToPalette(assembly);
    }, [assembly]);

    const bitmapDimensions = useMemo<{ width: number, height: number }>(() => {
        const response = { width: 0, height: 0 };

        if (!header) return response;

        const width = new RegExp(/Width (\d+)/g).exec(header);
        if (width && width[0] && width[1]) response.width = parseInt(width[1]);
        
        const height = new RegExp(/Height (\d+)/g).exec(header);
        if (height && height[0] && height[1]) response.height = parseInt(height[1]);
        
        return response;
    }, [header]);
    
    const bitmap = useMemo<number[][]>(() => {
        if (!bitmapDimensions.height || !bitmapDimensions.width) return [];
        if (!assembly) return [];

        return assemblyToBitmap(assembly, bitmapDimensions.width);
    }, [bitmapDimensions, assembly]);

    return (
        <>
            <div>
                <input
                    type="radio"
                    id="load-from-random"
                    checked={type === 'random'}
                    onChange={() => setType('random')}
                />
                <label for="load-from-random">new</label>

                <input
                    type="radio"
                    id="load-from-files"
                    checked={type === 'files'}
                    onChange={() => {
                        setType('files');
                    }}
                />
                <label for="load-from-files">files</label>

                <input
                    type="radio"
                    id="load-from-storage"
                    disabled={!Boolean(window.localStorage.getItem("bitmap-assembly")) && !Boolean(window.localStorage.getItem("bitmap-header"))}
                    checked={type === 'storage'}
                    onChange={() => {
                        setHeader(window.localStorage.getItem("bitmap-header")!);
                        setAssembly(window.localStorage.getItem("bitmap-assembly")!);
                        setType('storage');
                    }}
                />
                <label for="load-from-storage">storage</label>
            </div>

            {type === 'files' && (
                <div class="load-from-files-container">
                    <div class="load-from-files">
                        <LoadFromFile
                            content={header}
                            accept=".h"
                            onChange={setHeader}
                        />

                        <LoadFromFile
                            content={assembly}
                            accept=".s"
                            onChange={setAssembly}
                        />
                    </div>

                    <div class="load-summary">
                        <span>Palettes parsed in asm: {palette.length}</span>
                        <span>Expected bitmap width from header: {bitmapDimensions.width}</span>
                        <span>Expected bitmap height from header: {bitmapDimensions.height}</span>
                        <span>Expected bitmap pixels from header: {bitmapDimensions.width * bitmapDimensions.height}</span>
                        <span>Bitmap pixels parsed in asm: {bitmap.length * (bitmap.length ? bitmap[0].length : 0)}</span>
                    </div>
                </div>
            )}

            <button
                onClick={() => onLoad(palette, bitmap)}
            >
                Let's go!
            </button>
        </>
    );
}
